(()=>{'use strict';
const S=window.POSIXShell,P=S.P;
const U={};
U.need=(a,msg)=>{if(!a.length)throw Error(msg)};
U.node=p=>{let q=P.resolve(p),n=P.fs.get(q);if(!n)throw Error(p+': No such file or directory');return[q,n]};
U.parent=p=>P.norm(p).split('/').slice(0,-1).join('/')||'/';
U.bytes=n=>n?.t==='b'?(n.d?.byteLength||0):n?.t==='f'?new TextEncoder().encode(String(n.d||'')).length:n?.t==='l'?String(n.target||'').length:0;
U.clone=n=>n.t==='b'?{...n,d:new Uint8Array(n.d||0),time:Date.now()}:{...n,time:Date.now()};
U.copyTree=(src,dst)=>{let[sp,sn]=U.node(src),dp=P.norm(dst);if(sn.t!=='d'){P.md(U.parent(dp));P.fs.set(dp,U.clone(sn));return}P.md(dp);let prefix=sp==='/'?'/':sp+'/';for(let[k,n]of[...P.fs])if(k.startsWith(prefix)){let rel=k.slice(prefix.length),to=P.norm(dp+'/'+rel);if(n.t==='d')P.md(to);else{P.md(U.parent(to));P.fs.set(to,U.clone(n))}}};
U.removeTree=path=>{let p=P.norm(path),n=P.fs.get(p);if(!n)throw Error(path+': No such file or directory');if(p==='/')throw Error('refusing to remove /');for(let k of[...P.fs.keys()])if(k===p||k.startsWith(p+'/'))P.fs.delete(k)};
U.sizeOf=path=>{let p=P.norm(path),n=P.fs.get(p);if(!n)return 0;if(n.t!=='d')return U.bytes(n);let q=p==='/'?'/':p+'/',sum=0;for(let[k,x]of P.fs)if(k.startsWith(q))sum+=U.bytes(x);return sum};
S.fsutil=U;
})();
